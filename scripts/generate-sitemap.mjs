/**
 * Generates public/sitemap.xml from the route list in src/lib/seo.ts.
 *
 * Generated rather than hand-written for two reasons. `lastmod` is the one
 * sitemap field search engines still act on, and a hand-maintained date is
 * wrong the day after it is written. And a hand-maintained URL list eventually
 * picks up a private route by accident — here the list IS the one the app uses
 * to decide what is public, so the two cannot drift apart.
 *
 * Runs as part of `npm run build`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'src/lib/seo.ts'), 'utf8');

const SITE_URL = source.match(/export const SITE_URL = '([^']+)'/)?.[1];
if (!SITE_URL) throw new Error('Could not read SITE_URL from src/lib/seo.ts');

// Parse the PUBLIC_ROUTES literal rather than importing the module: this script
// runs under plain Node, before any TypeScript has been compiled.
const block = source.match(/export const PUBLIC_ROUTES[^=]*=\s*\[([\s\S]*?)\n\];/)?.[1];
if (!block) throw new Error('Could not read PUBLIC_ROUTES from src/lib/seo.ts');

const routes = [...block.matchAll(/\{\s*path:\s*'([^']+)',\s*priority:\s*([\d.]+),\s*changefreq:\s*'([^']+)'\s*\}/g)]
  .map(([, path, priority, changefreq]) => ({ path, priority, changefreq }));

if (!routes.length) throw new Error('PUBLIC_ROUTES parsed as empty — refusing to write an empty sitemap');

const lastmod = new Date().toISOString().slice(0, 10);

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes
  .map(
    (r) => `  <url>
    <loc>${SITE_URL}${r.path === '/' ? '/' : r.path}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${r.changefreq}</changefreq>
    <priority>${r.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`;

writeFileSync(resolve(root, 'public/sitemap.xml'), xml);
console.log(`sitemap.xml: ${routes.length} public routes, lastmod ${lastmod}`);
